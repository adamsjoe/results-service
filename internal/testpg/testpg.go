//go:build integration

// Package testpg gives each integration test package its own Postgres
// database, so packages can run in parallel without seeing each other's data.
//
// It uses the server at TEST_DATABASE_URL when set (as `make test` does);
// otherwise it starts a Postgres container with testcontainers-go (as CI
// does). The user must be able to create databases.
package testpg

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"net/url"
	"os"

	"github.com/jackc/pgx/v5"
	"github.com/testcontainers/testcontainers-go"
	"github.com/testcontainers/testcontainers-go/modules/postgres"
)

// Database is a freshly created, empty database.
type Database struct {
	URL      string // connection URL for this database
	name     string
	adminURL string // the server's default database, used for admin commands
	stop     func()
}

// Start creates a new database and returns it. Call Close when done.
func Start(ctx context.Context) (*Database, error) {
	adminURL := os.Getenv("TEST_DATABASE_URL")
	stop := func() {}
	if adminURL == "" {
		ctr, err := postgres.Run(ctx, "postgres:17-alpine",
			postgres.WithDatabase("test"),
			postgres.WithUsername("test"),
			postgres.WithPassword("test"),
			postgres.BasicWaitStrategies(),
		)
		if err != nil {
			return nil, fmt.Errorf("start postgres container: %w", err)
		}
		stop = func() { _ = testcontainers.TerminateContainer(ctr) }
		if adminURL, err = ctr.ConnectionString(ctx, "sslmode=disable"); err != nil {
			stop()
			return nil, err
		}
	}

	suffix := make([]byte, 6)
	if _, err := rand.Read(suffix); err != nil {
		stop()
		return nil, err
	}
	d := &Database{name: "test_" + hex.EncodeToString(suffix), adminURL: adminURL, stop: stop}

	if err := d.admin(ctx, "CREATE DATABASE "+d.name); err != nil {
		stop()
		return nil, err
	}

	u, err := url.Parse(adminURL)
	if err != nil {
		d.Close()
		return nil, err
	}
	u.Path = "/" + d.name
	d.URL = u.String()
	return d, nil
}

// Close drops the database and stops the container, if one was started.
func (d *Database) Close() {
	_ = d.admin(context.Background(), "DROP DATABASE IF EXISTS "+d.name+" WITH (FORCE)")
	d.stop()
}

// Disconnect simulates a database outage: it drops every connection to the
// database and refuses new ones until Reconnect is called.
func (d *Database) Disconnect(ctx context.Context) error {
	if err := d.admin(ctx, "ALTER DATABASE "+d.name+" WITH ALLOW_CONNECTIONS false"); err != nil {
		return err
	}
	return d.admin(ctx, "SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = '"+d.name+"'")
}

// Reconnect ends a simulated outage.
func (d *Database) Reconnect(ctx context.Context) error {
	return d.admin(ctx, "ALTER DATABASE "+d.name+" WITH ALLOW_CONNECTIONS true")
}

// admin runs one statement on the server's default database. The database
// name is generated by Start, never user input, so concatenation is safe.
func (d *Database) admin(ctx context.Context, sql string) error {
	conn, err := pgx.Connect(ctx, d.adminURL)
	if err != nil {
		return fmt.Errorf("connect as admin: %w", err)
	}
	defer func() { _ = conn.Close(context.Background()) }()
	if _, err := conn.Exec(ctx, sql); err != nil {
		return fmt.Errorf("%s: %w", sql, err)
	}
	return nil
}
